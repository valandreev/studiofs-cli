use super::{
    AccessLevel, FileType, Ino, InodeAttr, MetaError, Ordering, ROOT_INO, StudioVfs, VfsError,
    VfsResult, is_blocked_root_macos_metadata, is_ignored_macos_metadata,
    is_probable_trash_component,
};
use std::collections::{HashMap, HashSet};
use std::time::{Duration, Instant};

const DETACHED_IGNORED_ENTRY_RETENTION: Duration = Duration::from_secs(30);
#[cfg(not(test))]
const MAX_DETACHED_IGNORED_ENTRIES: usize = 4096;
#[cfg(test)]
const MAX_DETACHED_IGNORED_ENTRIES: usize = 4;

/// What a synthesized trash child reads from.
#[derive(Debug, Clone)]
pub(super) enum TrashViewBacking {
    /// Generated bytes, such as a Windows `$I` or Linux `.trashinfo` record.
    Bytes { receipt: Ino, data: Vec<u8> },
    /// The retained payload of this receipt.
    Payload { receipt: Ino },
    /// A nested child entry inside a retained directory view.
    Subtree {
        receipt: Ino,
        source_ino: Ino,
        parent_source_ino: Ino,
    },
    /// Synthesized trash root when no persistent root dir exists (e.g. read-only cross-OS view).
    VirtualTrashRoot,
    /// Synthesized Linux `.Trash-<uid>/files` container directory.
    LinuxFilesDir,
    /// Synthesized Linux `.Trash-<uid>/info` container directory.
    LinuxInfoDir,
    /// Synthesized, always-empty Linux `.Trash-<uid>/expunged` (GVFS delete sink).
    LinuxExpungedDir,
    /// Synthesized macOS `.Trashes/<uid>` container directory.
    MacOsUserDir,
}

#[derive(Debug, Clone)]
pub(super) struct IgnoredEntry {
    pub(super) attr: InodeAttr,
    pub(super) parent: Ino,
    pub(super) name: Vec<u8>,
    detached_at: Option<Instant>,
    /// `None` for a plain ignored entry, which reads as zeros.
    pub(super) view: Option<TrashViewBacking>,
}

#[derive(Debug, Default)]
pub(super) struct IgnoredEntryRegistry {
    pub(super) by_ino: HashMap<Ino, IgnoredEntry>,
    pub(super) by_name: HashMap<(Ino, Vec<u8>), Ino>,
    pub(super) children_by_parent: HashMap<Ino, HashSet<Ino>>,
}

fn remove_parent_child_link(registry: &mut IgnoredEntryRegistry, parent: Ino, child: Ino) {
    if let Some(children) = registry.children_by_parent.get_mut(&parent) {
        children.remove(&child);
        if children.is_empty() {
            registry.children_by_parent.remove(&parent);
        }
    }
}

fn prune_detached_entries(registry: &mut IgnoredEntryRegistry) {
    let now = Instant::now();
    let mut detached: Vec<(Ino, Instant)> = registry
        .by_ino
        .iter()
        .filter_map(|(ino, ignored)| ignored.detached_at.map(|detached_at| (*ino, detached_at)))
        .collect();

    let mut to_remove: HashSet<Ino> = detached
        .iter()
        .filter_map(|(ino, detached_at)| {
            (now.duration_since(*detached_at) >= DETACHED_IGNORED_ENTRY_RETENTION).then_some(*ino)
        })
        .collect();

    if detached.len() > MAX_DETACHED_IGNORED_ENTRIES {
        detached.sort_by_key(|(_, detached_at)| *detached_at);
        let overflow = detached.len() - MAX_DETACHED_IGNORED_ENTRIES;
        to_remove.extend(
            detached
                .into_iter()
                .take(overflow)
                .map(|(ino, _detached_at)| ino),
        );
    }

    for ino in to_remove {
        registry.by_ino.remove(&ino);
        registry.children_by_parent.remove(&ino);
    }
}

pub(super) fn retained_view_receipt(ignored: &IgnoredEntry) -> Option<Ino> {
    match &ignored.view {
        Some(TrashViewBacking::Bytes { receipt, .. })
        | Some(TrashViewBacking::Payload { receipt })
        | Some(TrashViewBacking::Subtree { receipt, .. }) => Some(*receipt),
        Some(
            TrashViewBacking::VirtualTrashRoot
            | TrashViewBacking::LinuxFilesDir
            | TrashViewBacking::LinuxInfoDir
            | TrashViewBacking::LinuxExpungedDir
            | TrashViewBacking::MacOsUserDir,
        )
        | None => None,
    }
}

impl StudioVfs {
    pub(super) fn ignored_entry_attr(&self, ino: Ino) -> Option<InodeAttr> {
        self.state
            .metrics
            .ignored_entries
            .lock()
            .by_ino
            .get(&ino)
            .map(|ignored| ignored.attr.clone())
    }

    pub(super) fn ignored_dir_attr(&self, ino: Ino) -> Option<InodeAttr> {
        let registry = self.state.metrics.ignored_entries.lock();
        let ignored = registry.by_ino.get(&ino)?;
        (ignored.attr.kind == FileType::Directory && ignored.view.is_none())
            .then(|| ignored.attr.clone())
    }

    pub fn is_synthesized_ignored_ino(&self, ino: Ino) -> bool {
        ino >= super::FIRST_IGNORED_INO && !self.is_runtime_stats_file_ino(ino)
    }

    pub(super) fn is_retained_view_ino(&self, ino: Ino) -> bool {
        if ino < super::FIRST_IGNORED_INO {
            return false;
        }
        self.state
            .metrics
            .ignored_entries
            .lock()
            .by_ino
            .get(&ino)
            .is_some_and(|ignored| retained_view_receipt(ignored).is_some())
    }

    pub(super) fn is_trash_container_ignored_ino(&self, ino: Ino) -> bool {
        if ino < super::FIRST_IGNORED_INO {
            return false;
        }
        self.state
            .metrics
            .ignored_entries
            .lock()
            .by_ino
            .get(&ino)
            .is_some_and(|ignored| {
                matches!(
                    ignored.view,
                    Some(
                        TrashViewBacking::VirtualTrashRoot
                            | TrashViewBacking::LinuxFilesDir
                            | TrashViewBacking::LinuxInfoDir
                            | TrashViewBacking::LinuxExpungedDir
                            | TrashViewBacking::MacOsUserDir
                    )
                )
            })
    }

    /// Generated `$I` / `.trashinfo` bytes change without a write (for example when a Clear
    /// deletes a child or a collision renames entries), so bridges must not serve them from an OS cache.
    pub fn is_generated_trash_record_ino(&self, ino: Ino) -> bool {
        ino >= super::FIRST_IGNORED_INO
            && self
                .state
                .metrics
                .ignored_entries
                .lock()
                .by_ino
                .get(&ino)
                .is_some_and(|ignored| matches!(ignored.view, Some(TrashViewBacking::Bytes { .. })))
    }

    pub(super) fn write_ignored_entry(
        &self,
        ino: Ino,
        offset: u64,
        data_len: usize,
    ) -> VfsResult<u32> {
        let ignored = self.visible_ignored_entry_snapshot(ino)?;
        if ignored.view.is_some() {
            return Err(VfsError::OperationNotSupported);
        }
        if data_len == 0 {
            return Ok(0);
        }
        let size = offset.saturating_add(data_len as u64);
        let _ = self.update_ignored_entry(ino, |attr| {
            if size > attr.size {
                attr.size = size;
                attr.committed_size = size;
            }
            attr.touch_mtime();
        });
        Ok(data_len as u32)
    }

    /// A subtree view names a live child only while its retained binding still
    /// resolves to the same inode; a deleted or replaced child is hidden.
    pub(super) fn subtree_view_child_is_live(
        &self,
        parent_source_ino: Ino,
        name: &[u8],
        source_ino: Ino,
    ) -> bool {
        self.sync_meta()
            .lookup(parent_source_ino, name)
            .is_ok_and(|entry| entry.ino == source_ino)
    }

    pub(super) fn collect_trash_view_dir_inos_for_receipt(&self, receipt: Ino) -> Vec<Ino> {
        let registry = self.state.metrics.ignored_entries.lock();
        registry
            .by_ino
            .values()
            .filter(|ignored| {
                ignored.attr.kind == FileType::Directory
                    && retained_view_receipt(ignored) == Some(receipt)
            })
            .map(|ignored| ignored.attr.ino)
            .collect()
    }

    pub(super) fn ignored_entry_lookup(&self, parent: Ino, name: &[u8]) -> Option<IgnoredEntry> {
        let key = (parent, name.to_vec());
        let registry = self.state.metrics.ignored_entries.lock();
        let ino = registry.by_name.get(&key).copied()?;
        registry.by_ino.get(&ino).cloned()
    }

    pub(super) fn ignored_entry(&self, ino: Ino) -> Option<IgnoredEntry> {
        self.state
            .metrics
            .ignored_entries
            .lock()
            .by_ino
            .get(&ino)
            .cloned()
    }

    pub(super) fn ignored_entry_has_retained_view(&self, parent: Ino, name: &[u8]) -> bool {
        let registry = self.state.metrics.ignored_entries.lock();
        let Some(ino) = registry.by_name.get(&(parent, name.to_vec())) else {
            return false;
        };
        let Some(ignored) = registry.by_ino.get(ino) else {
            return false;
        };
        ignored.parent == parent && ignored.name == name && retained_view_receipt(ignored).is_some()
    }

    pub(super) fn ensure_ignored_entry_snapshot_visible(
        &self,
        ignored: &IgnoredEntry,
    ) -> VfsResult<()> {
        match &ignored.view {
            Some(TrashViewBacking::Subtree {
                receipt,
                source_ino,
                parent_source_ino,
            }) => {
                if !self.subtree_view_child_is_live(*parent_source_ino, &ignored.name, *source_ino)
                    || self
                        .trash_view_receipt_access_by_receipt(*receipt)?
                        .is_none()
                {
                    return Err(Self::ignored_entry_not_found(ignored.parent, &ignored.name));
                }
            }
            _ => {
                if let Some(receipt) = retained_view_receipt(ignored) {
                    self.ensure_retained_view_receipt_visible(
                        ignored.parent,
                        &ignored.name,
                        receipt,
                    )?;
                }
            }
        }
        Ok(())
    }

    pub(super) fn visible_ignored_entry_snapshot(&self, ino: Ino) -> VfsResult<IgnoredEntry> {
        let ignored = self
            .ignored_entry(ino)
            .ok_or(VfsError::Meta(MetaError::InodeNotFound(ino)))?;
        self.ensure_ignored_entry_snapshot_visible(&ignored)?;
        Ok(ignored)
    }

    pub(super) fn ignored_entry_real_parent(&self, ignored: &IgnoredEntry) -> VfsResult<Ino> {
        let mut current = ignored.parent;
        let mut hops = 0usize;
        while current >= super::FIRST_IGNORED_INO {
            if hops >= 4096 {
                return Err(VfsError::Meta(MetaError::InodeNotFound(ignored.attr.ino)));
            }
            let Some(parent_entry) = self.ignored_entry(current) else {
                return Err(VfsError::Meta(MetaError::InodeNotFound(ignored.attr.ino)));
            };
            current = parent_entry.parent;
            hops += 1;
        }
        Ok(current)
    }

    pub(super) fn ignored_entry_snapshot_access_level(
        &self,
        ignored: &IgnoredEntry,
    ) -> VfsResult<AccessLevel> {
        if let Some(TrashViewBacking::Subtree {
            receipt,
            source_ino,
            parent_source_ino,
        }) = &ignored.view
        {
            if !self.subtree_view_child_is_live(*parent_source_ino, &ignored.name, *source_ino) {
                return Ok(AccessLevel::NoAccess);
            }
            return Ok(match self.trash_view_receipt_access_by_receipt(*receipt)? {
                Some(access) => access,
                None => AccessLevel::NoAccess,
            });
        }
        if let Some(receipt) = retained_view_receipt(ignored) {
            return Ok(match self.trash_view_receipt_access_by_receipt(receipt)? {
                Some(access)
                    if self.trash_entry_matches_receipt(
                        ignored.parent,
                        &ignored.name,
                        receipt,
                    )? =>
                {
                    access
                }
                _ => AccessLevel::NoAccess,
            });
        }
        let real_parent = self.ignored_entry_real_parent(ignored)?;
        if real_parent == 0 {
            return Ok(AccessLevel::ReadWrite);
        }
        self.effective_access_level(real_parent)
    }

    /// Returns the existing ignored entry at `(parent, name)` if it is publicly visible.
    ///
    /// A warmed generated trash entry whose snapshot is no longer visible is
    /// unlinked from `(parent, name)` and `None` is returned so public callers
    /// never reuse or observe its cached metadata.
    pub(super) fn lookup_public_ignored_entry(
        &self,
        parent: Ino,
        name: &[u8],
    ) -> Option<IgnoredEntry> {
        let existing = self.ignored_entry_lookup(parent, name)?;
        if retained_view_receipt(&existing).is_some()
            && self
                .ensure_ignored_entry_snapshot_visible(&existing)
                .is_err()
        {
            self.unlink_ignored_entry_if_matches(parent, name, existing.attr.ino);
            return None;
        }
        Some(existing)
    }

    fn ensure_retained_view_receipt_visible(
        &self,
        parent: Ino,
        name: &[u8],
        receipt: Ino,
    ) -> VfsResult<()> {
        if self
            .trash_view_receipt_access_by_receipt(receipt)?
            .is_none()
            || !self.trash_entry_matches_receipt(parent, name, receipt)?
        {
            return Err(Self::ignored_entry_not_found(parent, name));
        }
        Ok(())
    }

    pub(super) fn create_public_ignored_entry(
        &self,
        parent: Ino,
        name: &[u8],
        uid: u32,
        gid: u32,
        mode: u16,
        kind: FileType,
    ) -> InodeAttr {
        let _ = self.lookup_public_ignored_entry(parent, name);
        self.create_ignored_entry(parent, name, uid, gid, mode, kind)
    }

    pub(super) fn create_ignored_entry(
        &self,
        parent: Ino,
        name: &[u8],
        uid: u32,
        gid: u32,
        mode: u16,
        kind: FileType,
    ) -> InodeAttr {
        let mut registry = self.state.metrics.ignored_entries.lock();
        prune_detached_entries(&mut registry);
        let key = (parent, name.to_vec());
        if let Some(ino) = registry.by_name.get(&key).copied()
            && let Some(existing) = registry.by_ino.get(&ino)
        {
            return existing.attr.clone();
        }

        let ino = self
            .state
            .metrics
            .next_ignored_ino
            .fetch_add(1, Ordering::Relaxed);
        let attr = match kind {
            FileType::Directory => InodeAttr::new_dir(ino, parent, uid, gid, mode & 0o7777),
            FileType::RegularFile => InodeAttr::new_file(ino, parent, uid, gid, mode & 0o7777),
            FileType::Symlink => InodeAttr::new_symlink(ino, parent, uid, gid, 0),
        };
        let ignored = IgnoredEntry {
            attr: attr.clone(),
            parent,
            name: key.1.clone(),
            detached_at: None,
            view: None,
        };
        registry.by_name.insert(key, ino);
        registry
            .children_by_parent
            .entry(parent)
            .or_default()
            .insert(ino);
        registry.by_ino.insert(ino, ignored);
        attr
    }

    /// Local, unpublished entry for a trash view (`$R`, `$I`, or a nested
    /// directory/file inside a `$R` directory view).
    #[allow(clippy::too_many_arguments)]
    pub(super) fn upsert_ignored_view_entry(
        &self,
        parent: Ino,
        name: &[u8],
        kind: FileType,
        mode: u16,
        attr_template: Option<&InodeAttr>,
        size: u64,
        view: Option<TrashViewBacking>,
    ) -> InodeAttr {
        let profile = self.native_trash_profile();
        let mut registry = self.state.metrics.ignored_entries.lock();
        prune_detached_entries(&mut registry);
        let key = (parent, name.to_vec());
        let ino = if let Some(&existing_ino) = registry.by_name.get(&key) {
            existing_ino
        } else {
            let new_ino = self
                .state
                .metrics
                .next_ignored_ino
                .fetch_add(1, Ordering::Relaxed);
            registry.by_name.insert(key.clone(), new_ino);
            registry
                .children_by_parent
                .entry(parent)
                .or_default()
                .insert(new_ino);
            new_ino
        };
        let mut attr = match kind {
            FileType::Directory => InodeAttr::new_dir(ino, parent, 0, 0, mode & 0o7777),
            FileType::RegularFile => InodeAttr::new_file(ino, parent, 0, 0, mode & 0o7777),
            FileType::Symlink => {
                InodeAttr::new_symlink(ino, parent, 0, 0, size.try_into().unwrap_or(usize::MAX))
            }
        };
        attr.size = size;
        attr.committed_size = size;
        if let super::NativeTrashProfile::Linux { uid } = profile {
            attr.uid = uid;
            attr.gid = uid;
        }
        if let Some(template) = attr_template {
            attr.atime = template.atime;
            attr.mtime = template.mtime;
            attr.ctime = template.ctime;
            attr.crtime = template.crtime;
        }
        let ignored = IgnoredEntry {
            attr: attr.clone(),
            parent,
            name: key.1,
            detached_at: None,
            view,
        };
        registry.by_ino.insert(ino, ignored);
        attr
    }

    /// Fills `buffer` from a prevalidated ignored-entry snapshot at `offset`.
    /// A `$R` view reads its retained payload and propagates its errors; a `$I`
    /// record copies its bytes; a plain ignored entry reads as zeros. Callers
    /// pass a range already clamped to the snapshot's `attr.size`.
    pub(super) async fn read_ignored_entry_snapshot_into(
        &self,
        ignored: &IgnoredEntry,
        offset: u64,
        buffer: &mut [u8],
    ) -> VfsResult<u32> {
        self.ensure_ignored_entry_snapshot_visible(ignored)?;
        match &ignored.view {
            Some(TrashViewBacking::Payload { receipt })
            | Some(TrashViewBacking::Subtree { receipt, .. }) => {
                // Boxed: the payload read re-enters `read_into_impl`, which reaches here.
                return Box::pin(self.read_trash_view_snapshot(ignored, *receipt, offset, buffer))
                    .await;
            }
            _ => {}
        }
        buffer.fill(0);
        if let Some(TrashViewBacking::Bytes { data: bytes, .. }) = &ignored.view {
            let start = (offset as usize).min(bytes.len());
            let n = buffer.len().min(bytes.len() - start);
            buffer[..n].copy_from_slice(&bytes[start..start + n]);
        }
        Ok(buffer.len() as u32)
    }

    pub(super) fn update_ignored_entry<F>(&self, ino: Ino, update: F) -> Option<InodeAttr>
    where
        F: FnOnce(&mut InodeAttr),
    {
        let mut registry = self.state.metrics.ignored_entries.lock();
        let ignored = registry.by_ino.get_mut(&ino)?;
        update(&mut ignored.attr);
        Some(ignored.attr.clone())
    }

    pub(super) fn clear_trash_view_ignored_entries(&self) {
        let mut registry = self.state.metrics.ignored_entries.lock();
        let view_inos: Vec<(Ino, Ino, Vec<u8>)> = registry
            .by_ino
            .iter()
            .filter(|(_, ignored)| ignored.view.is_some())
            .map(|(ino, ignored)| (*ino, ignored.parent, ignored.name.clone()))
            .collect();
        for (ino, parent, name) in view_inos {
            let key = (parent, name);
            if registry.by_name.get(&key).copied() == Some(ino) {
                registry.by_name.remove(&key);
            }
            remove_parent_child_link(&mut registry, parent, ino);
            registry.children_by_parent.remove(&ino);
            if self.handle_table.open_count(ino) > 0 {
                self.handle_table.mark_orphan(ino);
            } else {
                registry.by_ino.remove(&ino);
            }
        }
    }

    fn unlink_ignored_entry_locked(
        &self,
        registry: &mut IgnoredEntryRegistry,
        parent: Ino,
        name: &[u8],
        expected_ino: Option<Ino>,
    ) -> bool {
        let key = (parent, name.to_vec());
        let Some(&ino) = registry.by_name.get(&key) else {
            return false;
        };
        if let Some(expected) = expected_ino
            && ino != expected
        {
            return false;
        }
        registry.by_name.remove(&key);
        remove_parent_child_link(registry, parent, ino);

        if self.handle_table.open_count(ino) > 0 {
            self.handle_table.mark_orphan(ino);
        } else {
            registry.by_ino.remove(&ino);
        }
        true
    }

    pub(super) fn unlink_ignored_entry_if_matches(
        &self,
        parent: Ino,
        name: &[u8],
        expected_ino: Ino,
    ) -> bool {
        let mut registry = self.state.metrics.ignored_entries.lock();
        self.unlink_ignored_entry_locked(&mut registry, parent, name, Some(expected_ino))
    }

    pub(super) fn unlink_ignored_entry(&self, parent: Ino, name: &[u8]) -> bool {
        let mut registry = self.state.metrics.ignored_entries.lock();
        self.unlink_ignored_entry_locked(&mut registry, parent, name, None)
    }

    pub(super) fn unlink_ignored_subtree(&self, parent: Ino, name: &[u8]) -> bool {
        let key = (parent, name.to_vec());
        let mut registry = self.state.metrics.ignored_entries.lock();
        let Some(root_ino) = registry.by_name.remove(&key) else {
            return false;
        };

        let mut pending = vec![root_ino];
        let mut to_remove = Vec::new();
        while let Some(current) = pending.pop() {
            to_remove.push(current);
            if let Some(children) = registry.children_by_parent.get(&current) {
                pending.extend(children.iter().copied());
            }
        }

        for ino in to_remove {
            if let Some(ignored) = registry.by_ino.get(&ino).cloned() {
                registry
                    .by_name
                    .remove(&(ignored.parent, ignored.name.clone()));
                remove_parent_child_link(&mut registry, ignored.parent, ino);
                registry.children_by_parent.remove(&ino);
                if self.handle_table.open_count(ino) > 0 {
                    self.handle_table.mark_orphan(ino);
                } else {
                    registry.by_ino.remove(&ino);
                }
            }
        }
        true
    }

    pub(super) fn release_ignored_entry(&self, ino: Ino) -> bool {
        let mut registry = self.state.metrics.ignored_entries.lock();
        let Some(ignored) = registry.by_ino.remove(&ino) else {
            return false;
        };
        let key = (ignored.parent, ignored.name);
        if registry.by_name.get(&key).copied() == Some(ino) {
            registry.by_name.remove(&key);
        }
        remove_parent_child_link(&mut registry, ignored.parent, ino);
        registry.children_by_parent.remove(&ino);
        true
    }

    pub(super) fn detach_ignored_entry_name(&self, ino: Ino) -> bool {
        let mut registry = self.state.metrics.ignored_entries.lock();
        let Some(ignored) = registry.by_ino.get(&ino).cloned() else {
            return false;
        };
        let key = (ignored.parent, ignored.name);
        if registry.by_name.get(&key).copied() == Some(ino) {
            registry.by_name.remove(&key);
        }
        remove_parent_child_link(&mut registry, ignored.parent, ino);
        if let Some(ignored) = registry.by_ino.get_mut(&ino) {
            ignored.detached_at = Some(Instant::now());
        }
        prune_detached_entries(&mut registry);
        true
    }

    pub(super) fn ignored_entry_not_found(parent: Ino, name: &[u8]) -> VfsError {
        VfsError::Meta(MetaError::EntryNotFound {
            parent,
            name: String::from_utf8_lossy(name).into_owned(),
        })
    }

    pub(super) fn is_blocked_root_metadata_path(&self, parent: Ino, name: &[u8]) -> bool {
        parent == ROOT_INO && is_blocked_root_macos_metadata(name)
    }

    pub(super) fn should_ignore_regular_file_path(&self, parent: Ino, name: &[u8]) -> bool {
        is_ignored_macos_metadata(name)
            || self.is_blocked_root_metadata_path(parent, name)
            || self.ignored_dir_attr(parent).is_some()
            || self.is_trash_sidecar_draft(parent, name)
            || self.is_macos_trash_metadata_entry(parent, name)
    }

    pub(super) fn should_ignore_directory_path(&self, parent: Ino, name: &[u8]) -> bool {
        self.is_blocked_root_metadata_path(parent, name) || self.ignored_dir_attr(parent).is_some()
    }

    pub(super) fn ignored_directory_has_probable_trash_ancestor(&self, dir_ino: Ino) -> bool {
        let mut current = dir_ino;
        let mut hops = 0usize;
        while current != 0 && hops < 1024 {
            let Some(entry) = self.ignored_entry(current) else {
                break;
            };
            if entry.parent == ROOT_INO && is_probable_trash_component(&entry.name) {
                return true;
            }
            current = entry.parent;
            hops += 1;
        }
        false
    }
}

