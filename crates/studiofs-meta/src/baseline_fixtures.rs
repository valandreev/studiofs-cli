fn read_fixture(path: &Path) -> Vec<u8> {
    std::fs::read(path).unwrap_or_else(|err| panic!("read fixture {}: {err}", path.display()))
}

/// Copies a redb fixture so tests never open the pinned file for writing.
fn copy_to_temp(fixture: &Path) -> (tempfile::TempDir, PathBuf) {
    let dir = studiofs_test_support::workspace_target_tempdir("baseline-fixture-");
    let path = dir.path().join("fixture.redb");
    studiofs_test_support::copy_file_contents(fixture, &path)
        .unwrap_or_else(|err| panic!("copy fixture {}: {err}", fixture.display()));
    (dir, path)
}

