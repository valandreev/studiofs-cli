#[test]
fn baseline_events_decode_one_per_tag() {
    let dir = fixture_dir().join("events");
    let events = fixture_events();
    let mut tags: Vec<u8> = events.iter().map(|(_, tag, _)| *tag).collect();
    tags.sort_unstable();
    assert_eq!(
        tags,
        [(1..=15).collect::<Vec<u8>>(), vec![18, 19, 20, 21]].concat()
    );
    for (file, tag, expected) in events {
        let bytes = read_fixture(&dir.join(file));
        assert_eq!(&bytes[..7], b"SFS-EVT", "{file}: wire magic");
        assert_eq!(bytes[7], 1, "{file}: wire version");
        assert_eq!(bytes[8], tag, "{file}: kind tag");
        assert_eq!(decode_event(&bytes).expect(file), expected, "{file}");
        // RemoveLocalEntry is journal-only and never published to PostgreSQL.
        if tag != 18 {
            assert_eq!(
                decode_event_with_type(expected.kind(), &bytes).expect(file),
                expected,
                "{file}: PostgreSQL event_type decode"
            );
        }
    }
}

