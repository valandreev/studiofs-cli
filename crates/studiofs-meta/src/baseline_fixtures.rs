const REGENERATE_ENV: &str = "STUDIOFS_REGENERATE_BASELINE_FIXTURES";
/// Fixed timestamp (2025-11-24T16:00:00Z) so regenerated bytes are stable.
const FIXTURE_TIME_NS: i64 = 1_764_000_000_000_000_000;
/// Test-only volume master key; it protects no real data.
const FIXTURE_MASTER_KEY: [u8; ENCRYPTION_KEY_LENGTH] = [0x5A; ENCRYPTION_KEY_LENGTH];
/// PostgreSQL batch version the local fixtures have replayed through.
const FIXTURE_REPLAY_CURSOR: u64 = 7;

