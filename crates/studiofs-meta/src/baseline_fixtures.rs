//! Pinned 0.2.5 baseline persisted-format fixtures (SFS-1002).
//!
//! The files live in `tests/fixtures/baseline-0.2.5/` and are listed with their
//! SHA-256 in `manifest.json` there. Normal test runs only read them. The
//! generator below rewrites them and runs only when
//! `STUDIOFS_REGENERATE_BASELINE_FIXTURES=1` is set together with `--ignored`;
//! regenerate only with the baseline encoder and record the reason in the
//! manifest.

