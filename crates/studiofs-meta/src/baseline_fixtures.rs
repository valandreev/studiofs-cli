#[test]
fn baseline_clean_cache_has_no_unpublished_journal() {
    let (_dir, path) = copy_to_temp(&fixture_dir().join("local-clean.redb"));
    let engine = RedbMetaEngine::open(&path).expect("open clean cache");
    assert_published_namespace(&engine);
    assert_eq!(
        read_counter(&engine, crate::pg_engine::LOCAL_PG_VERSION_COUNTER),
        FIXTURE_REPLAY_CURSOR
    );
    // Both positions are exclusive ends, normalized as the publisher reads them.
    let (local_end, acknowledged) = engine.local_outbound_ack_positions().unwrap();
    assert!(
        local_end <= acknowledged,
        "clean cache must not hold unpublished events: end {local_end}, acknowledged {acknowledged}"
    );
    assert!(engine.read_events_range(0, u64::MAX).unwrap().is_empty());
}

#[test]
fn baseline_dirty_cache_keeps_unpublished_journal() {
    let (_dir, path) = copy_to_temp(&fixture_dir().join("local-dirty.redb"));
    let engine = RedbMetaEngine::open(&path).expect("open dirty cache");
    assert_published_namespace(&engine);
    assert_eq!(
        read_counter(&engine, crate::pg_engine::LOCAL_PG_VERSION_COUNTER),
        FIXTURE_REPLAY_CURSOR
    );
    assert_eq!(
        read_counter(&engine, counters::LOCAL_EVENT_LOG_PRUNED_THROUGH_SEQ),
        0,
        "local replay floor"
    );
    let (local_end, acknowledged) = engine.local_outbound_ack_positions().unwrap();
    assert!(
        local_end > acknowledged,
        "dirty cache must hold unacknowledged events: end {local_end}, acknowledged {acknowledged}"
    );
    let pending = engine.read_events_range(0, u64::MAX).unwrap();
    assert!(
        pending.iter().any(|event| matches!(
            event,
            MetaEvent::AddEntry { name, .. } if name == b"unpublished-dir"
        )),
        "unpublished mkdir must stay in the journal: {pending:?}"
    );
    assert!(pending.iter().any(|event| matches!(
        event,
        MetaEvent::SetVolumeSettings { settings } if settings.trash.days() == 14
    )));
    assert!(engine.lookup(ROOT_INO, b"unpublished-dir").is_ok());
    assert!(engine.lookup(DOCS_INO, b"unpublished.txt").is_ok());
}

#[test]
fn published_v0_2_2_format5_volume_requires_upgrade() {
    let dir = published_dir("v0.2.2");
    let bytes = read_fixture(&dir.join("format-info.json"));
    assert!(matches!(
        crate::decode_format_info(&bytes),
        Err(MetaError::UnsupportedFormatVersion {
            found: 5,
            expected: 6
        })
    ));
    let bytes = read_fixture(&dir.join("serving-checkpoint.bin"));
    let checkpoint = ServingCheckpoint::decode(&bytes).expect("v0.2.2 checkpoint decodes");
    // Checkpoint format 2: the format 1 tables plus directory aliases, with no
    // settings suffix, so settings decode as the default.
    let format_2 = postcard::to_stdvec(&(
        &checkpoint.inodes,
        &checkpoint.dentries,
        &checkpoint.regular_file_base,
        &checkpoint.symlinks,
        &checkpoint.xattrs,
        &checkpoint.acl_rules,
        &checkpoint.directory_aliases,
    ))
    .unwrap();
    assert_eq!(bytes, format_2, "v0.2.2 checkpoint is exactly format 2");
    assert_eq!(checkpoint.volume_settings, VolumeSettings::default());

    let (_tmp, path) = copy_to_temp(&dir.join("local-cache.redb"));
    assert!(matches!(
        RedbMetaEngine::read_format_info_readonly(&path),
        Err(MetaError::UnsupportedFormatVersion { found: 5, .. })
    ));
    let engine = RedbMetaEngine::open_for_format_upgrade(&path).expect("open for upgrade");
    assert_eq!(engine.format_info_for_upgrade().unwrap().format_version, 5);
}

