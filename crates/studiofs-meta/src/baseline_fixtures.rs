    let checkpoint = read_fixture(&dir.join("serving-checkpoint.bin"));
    // init publishes the checkpoint at version 0 and its settings as batch 1.
    let checkpoint = ServingCheckpoint::decode(&checkpoint).expect("format-6 checkpoint decodes");
    assert_eq!(checkpoint.volume_settings.revision, 0);

    #[derive(serde::Deserialize)]
    struct EventRow {
        event_type: String,
        event_payload_hex: String,
    }
    let rows: Vec<EventRow> =
        serde_json::from_slice(&read_fixture(&dir.join("event-log.json"))).unwrap();
    assert!(!rows.is_empty());
    for row in rows {
        let payload: Vec<u8> = (0..row.event_payload_hex.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&row.event_payload_hex[i..i + 2], 16).unwrap())
            .collect();
        let event =
            decode_event_with_type(&row.event_type, &payload).expect("published event decodes");
        assert!(matches!(
            event,
            MetaEvent::SetVolumeSettings { settings } if settings.compression.is_enabled()
        ));
    }

    let (_tmp, path) = copy_to_temp(&dir.join("local-cache.redb"));
    let local = RedbMetaEngine::read_format_info_readonly(&path).expect("local header decodes");
    assert_eq!(local.uuid, info.uuid);
