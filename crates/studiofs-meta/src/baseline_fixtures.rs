fn trash_7_days() -> TrashPolicy {
    let mut trash = TrashPolicy::default();
    trash.set_days(7);
    trash
}

/// Full 0.2.5 `VolumeSettings`: trash, quota and zstd compression.
pub(crate) fn fixture_volume_settings() -> VolumeSettings {
    VolumeSettings {
        revision: 3,
        trash: trash_7_days(),
        logical_quota_bytes: Some(1 << 30),
        compression: CompressionPolicy::zstd(3).expect("valid zstd level"),
    }
}

fn attr(ino: u64, parent: u64, kind: FileType, size: u64) -> InodeAttr {
    let (mode, nlink, win_attrs) = match kind {
        FileType::Directory => (0o755, 2, 0x10),
        FileType::RegularFile => (0o644, 1, 0x20),
        FileType::Symlink => (0o777, 1, 0x0400),
    };
    InodeAttr {
        ino,
        kind,
        mode,
        uid: 1000,
        gid: 1000,
        size,
        committed_size: size,
        nlink,
        mtime: FIXTURE_TIME_NS,
        ctime: FIXTURE_TIME_NS,
        atime: FIXTURE_TIME_NS,
        parent,
        crtime: FIXTURE_TIME_NS,
        win_attrs,
        content_epoch: 0,
        committed_content_epoch: 0,
        upload_state: UploadState::Ready,
    }
}

fn file_slices(state: PayloadRefState) -> Vec<(ChunkId, Vec<SliceRecord>)> {
    vec![(
        ChunkId(0),
        vec![SliceRecord {
            slice_id: SliceId(1),
            order: SliceOrder(1),
            range: SliceRange::new(0, FILE_LEN).expect("valid range"),
            payload: Some(PayloadRef::new_full(FILE_OBJECT_ID, FILE_LEN)),
            payload_state: state,
        }],
    )]
}

fn entry(ino: u64, kind: FileType) -> DirEntryValue {
    DirEntryValue { ino, kind }
}

