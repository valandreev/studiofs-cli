/// Builds a local cache that replayed the published namespace through
/// [`FIXTURE_REPLAY_CURSOR`]; nothing local is pending yet.
fn replayed_engine(path: &Path) -> RedbMetaEngine {
    let engine = RedbMetaEngine::open(path).expect("open fixture redb");
    engine
        .set_format_info(&fixture_format_info())
        .expect("set format info");
    let events = published_namespace_events();
    engine.apply_replica_events_to_base(&events).expect("base");
    engine.apply_replica_aux_state(&events).expect("aux");
    engine
        .apply_replica_serving_state(&events)
        .expect("serving");
    engine
        .set_counter(
            crate::pg_engine::LOCAL_PG_VERSION_COUNTER,
            FIXTURE_REPLAY_CURSOR,
        )
        .expect("replay cursor");
    engine
}

fn compact(path: &Path) {
    let mut db = redb::Database::open(path).expect("reopen for compaction");
    while db.compact().expect("compact fixture redb") {}
}

fn write_fixture(path: &Path, bytes: &[u8]) {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).expect("create fixture dir");
    }
    std::fs::write(path, bytes).unwrap_or_else(|err| panic!("write {}: {err}", path.display()));
}

#[test]
#[ignore = "rewrites pinned fixtures; set STUDIOFS_REGENERATE_BASELINE_FIXTURES=1"]
fn regenerate_baseline_0_2_5_fixtures() {
    if std::env::var_os(REGENERATE_ENV).is_none() {
        eprintln!("{REGENERATE_ENV} is not set; leaving pinned fixtures unchanged");
        return;
    }
    let dir = fixture_dir();
    write_fixture(
        &dir.join("format-info.json"),
        &serde_json::to_vec(&fixture_format_info()).expect("encode format info"),
    );
    write_fixture(
        &dir.join("volume-settings.json"),
        &serde_json::to_vec(&fixture_volume_settings()).expect("encode settings"),
    );
    for (file, _, event) in fixture_events() {
        write_fixture(
            &dir.join("events").join(file),
            &encode_event(&event).expect("encode event"),
        );
    }

    let work = studiofs_test_support::workspace_target_tempdir("baseline-fixture-gen-");
    let checkpoint = {
        let engine = replayed_engine(&work.path().join("source.redb"));
        engine
            .export_serving_checkpoint_bytes()
            .expect("export checkpoint")
    };
    write_fixture(&dir.join("serving-checkpoint.bin"), &checkpoint);

    // Snapshot artifact: a checkpoint import equivalent to an empty-tail
    // reconstruction (`reconstruct_loaded_snapshot_source` opens redb, sets the
    // format, imports the checkpoint, then replays zero rows). Unlike the
    // worker, the fixture is compacted to keep it small.
    let artifact = dir.join("snapshot-artifact.redb");
    let _ = std::fs::remove_file(&artifact);
    {
        let engine = RedbMetaEngine::open(&artifact).expect("open artifact");
        engine
            .set_format_info(&fixture_format_info())
            .expect("artifact format");
        engine
            .import_serving_checkpoint_bytes(&checkpoint)
            .expect("import checkpoint");
    }
    compact(&artifact);

    let clean = dir.join("local-clean.redb");
    let _ = std::fs::remove_file(&clean);
    drop(replayed_engine(&clean));
    compact(&clean);

    // Dirty cache: replayed state plus unpublished local mutations.
    let dirty = dir.join("local-dirty.redb");
    let _ = std::fs::remove_file(&dirty);
    {
        let engine = replayed_engine(&dirty);
        engine
            .create_dir_with_ino(10, ROOT_INO, b"unpublished-dir", 1000, 1000, 0o755)
            .expect("local mkdir");
        engine
            .create_file_with_ino(11, DOCS_INO, b"unpublished.txt", 1000, 1000, 0o644)
            .expect("local create");
        engine
            .set_xattr(FILE_INO, b"user.unpublished", b"pending", 0)
            .expect("local xattr");
        engine
            .compare_and_set_trash_days(fixture_volume_settings().revision, 14)
            .expect("local settings cas")
            .expect("settings revision accepted");
    }
    compact(&dirty);
}

fn read_counter(engine: &RedbMetaEngine, name: &str) -> u64 {
    engine.get_counter(name).expect("read counter")
}

fn assert_published_namespace(engine: &dyn MetaEngine) {
    let docs = engine.lookup(ROOT_INO, b"docs").expect("docs");
    assert_eq!((docs.ino, docs.kind), (DOCS_INO, FileType::Directory));
    let file = engine.lookup(DOCS_INO, b"final.txt").expect("final.txt");
    assert_eq!((file.ino, file.kind), (FILE_INO, FileType::RegularFile));
    assert_eq!(engine.get_attr(FILE_INO).expect("file attr").size, 4096);
    assert_eq!(
        engine.get_symlink_target(LINK_INO).expect("link target"),
        LINK_TARGET
    );
    assert_eq!(
        engine.get_xattr(FILE_INO, XATTR_NAME).expect("xattr"),
        Some(XATTR_VALUE.to_vec())
    );
    assert_eq!(
        engine.get_acl_rule(DOCS_INO, ACL_PRINCIPAL).expect("acl"),
        Some(AccessLevel::ReadOnly)
    );
}

