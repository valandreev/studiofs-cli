<#
.SYNOPSIS
  Capture persisted bytes of a volume formatted by a published StudioFS release.

.DESCRIPTION
  SFS-1002. For each release tag, downloads the published Windows binary with
  `gh release download`, verifies its SHA-256, starts an isolated PostgreSQL
  and RustFS pair in Docker (images from docker/compose.e2e.yml), formats a
  volume with that binary, and writes the persisted bytes to
  crates/studiofs-meta/tests/fixtures/published-<tag>/:

    format-info.json       metadata_state.format_info (shared FormatInfo JSON)
    serving-checkpoint.bin metadata_state.snapshot (serving checkpoint bytes)
    metadata-state.json    metadata_state scalar columns and schema components
    event-log.json         event_log rows written by init (hex payloads)
    local-cache.redb       the local redb metadata cache created by init

  Every credential is a throwaway local value: PostgreSQL runs with trust
  authentication (the DSN carries no password) and RustFS uses fixed
  test-only keys. The volume master key inside FormatInfo is generated by the
  published `init` for this throwaway volume and protects no data.

  After a run, update the SHA-256 values in
  crates/studiofs-meta/tests/fixtures/baseline-0.2.5/manifest.json (the drift
  test prints the actual digest) and record the reason for the capture.

.EXAMPLE
  pwsh tools/fixtures/capture-published-volume-fixtures.ps1
  pwsh tools/fixtures/capture-published-volume-fixtures.ps1 -Tags v0.2.4
#>
[CmdletBinding()]
param(
    [string[]] $Tags = @('v0.2.2', 'v0.2.4'),
    [int] $PostgresPort = 25532,
    [int] $RustfsPort = 29100,
    [int] $ReadyTimeoutSeconds = 120,
    [switch] $KeepContainers
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path
$workRoot = Join-Path $repoRoot 'target/sfs-1002-published'
$fixtureRoot = Join-Path $repoRoot 'crates/studiofs-meta/tests/fixtures'

# Keep in sync with docker/compose.e2e.yml and crates/studiofs-e2e/src/infra.rs.
$postgresImage = 'postgres:18-alpine'
$rustfsImage = 'rustfs/rustfs:latest'
$s3AccessKey = 'sfs-fixture-access'
$s3SecretKey = 'sfs-fixture-secret'

# Windows release asset names changed between releases.
$assetByTag = @{
    'v0.2.2' = 'studiofs-0.2.2-x86_64-pc-windows-msvc.zip'
    'v0.2.4' = 'studiofs-0.2.4-x86_64-pc-windows.zip'
}

function Invoke-Native {
    param([string] $What, [scriptblock] $Command)
    $output = & $Command 2>&1
    if ($LASTEXITCODE -ne 0) {
        throw "$What failed (exit $LASTEXITCODE): $($output | Out-String)"
    }
    $output
}

function Wait-Until {
    param([string] $What, [scriptblock] $Probe)
    $deadline = (Get-Date).AddSeconds($ReadyTimeoutSeconds)
    while ((Get-Date) -lt $deadline) {
        if (& $Probe) { return }
        Start-Sleep -Milliseconds 500 # bounded readiness poll of observable state
    }
    throw "$What did not become ready within $ReadyTimeoutSeconds s"
}

function Get-ReleaseBinary {
    param([string] $Tag)
    $asset = $assetByTag[$Tag]
    if (-not $asset) { throw "no Windows asset name recorded for $Tag" }
    $dir = Join-Path $workRoot $Tag
    New-Item -ItemType Directory -Force $dir | Out-Null
    Invoke-Native "download $Tag" { gh release download $Tag --pattern $asset --pattern "$asset.sha256" --dir $dir --clobber } | Out-Null
    $zip = Join-Path $dir $asset
    $expected = ((Get-Content "$zip.sha256" -Raw).Trim() -split '\s+')[0].ToLowerInvariant()
    $actual = (Get-FileHash -Algorithm SHA256 $zip).Hash.ToLowerInvariant()
    if ($expected -ne $actual) { throw "$asset SHA-256 mismatch: expected $expected, got $actual" }
    $bin = Join-Path $dir 'bin'
    Expand-Archive -Force $zip $bin
    $exe = Get-ChildItem -Recurse -Filter studiofs.exe $bin | Select-Object -First 1
    if (-not $exe) { throw "studiofs.exe not found in $asset" }
    [pscustomobject]@{ Exe = $exe.FullName; Asset = $asset; Sha256 = $actual }
}

function Invoke-Psql {
    param([string] $Container, [string] $Sql)
    (Invoke-Native "psql" { docker exec $Container psql -U studiofs -d studiofs -At -c $Sql }) -join "`n"
}

function Convert-HexToBytes {
    param([string] $Hex)
    $Hex = $Hex.Trim()
    $bytes = [byte[]]::new($Hex.Length / 2)
    for ($i = 0; $i -lt $bytes.Length; $i++) {
        $bytes[$i] = [Convert]::ToByte($Hex.Substring($i * 2, 2), 16)
    }
    , $bytes
}

foreach ($tag in $Tags) {
    $release = Get-ReleaseBinary $tag
    $suffix = $tag.Replace('.', '-')
    $pg = "sfs-1002-pg-$suffix"
    $s3 = "sfs-1002-rustfs-$suffix"
    $out = Join-Path $fixtureRoot "published-$tag"
    $clientRoot = Join-Path $workRoot "$tag/client"
    $volume = "fixture-$($suffix.TrimStart('v'))"

    docker rm -f $pg $s3 2>$null | Out-Null
    if (Test-Path $clientRoot) { Remove-Item -Recurse -Force $clientRoot }
    New-Item -ItemType Directory -Force $clientRoot, $out | Out-Null
    try {
        Invoke-Native 'start postgres' {
            docker run -d --name $pg -p "127.0.0.1:${PostgresPort}:5432" `
                -e POSTGRES_USER=studiofs -e POSTGRES_DB=studiofs -e POSTGRES_HOST_AUTH_METHOD=trust `
                $postgresImage
        } | Out-Null
        Invoke-Native 'start rustfs' {
            docker run -d --name $s3 -p "127.0.0.1:${RustfsPort}:9000" `
                -e RUSTFS_ADDRESS=:9000 -e RUSTFS_ACCESS_KEY=$s3AccessKey -e RUSTFS_SECRET_KEY=$s3SecretKey `
                $rustfsImage --address :9000 /data
        } | Out-Null
        Wait-Until 'postgres' {
            docker exec $pg pg_isready -U studiofs -d studiofs -h 127.0.0.1 2>$null | Out-Null
            $LASTEXITCODE -eq 0
        }
        Wait-Until 'rustfs' {
            try { (Invoke-WebRequest -UseBasicParsing -TimeoutSec 2 "http://127.0.0.1:$RustfsPort/health").StatusCode -eq 200 }
            catch { $false }
        }

        $env:STUDIOFS_CLIENT_ROOT = $clientRoot
        Invoke-Native "$tag init" {
            & $release.Exe init $volume --endpoint "http://127.0.0.1:$RustfsPort" --bucket sfs-fixture `
                --access-key $s3AccessKey --secret-key $s3SecretKey --region us-east-1 `
                --meta "postgres://studiofs@127.0.0.1:$PostgresPort"
        } | Out-Null

        $vol = Invoke-Psql $pg "SELECT vol FROM volumes WHERE name = '$volume'"
        [IO.File]::WriteAllBytes((Join-Path $out 'format-info.json'),
            (Convert-HexToBytes (Invoke-Psql $pg "SELECT encode(format_info, 'hex') FROM metadata_state WHERE vol = $vol")))
        [IO.File]::WriteAllBytes((Join-Path $out 'serving-checkpoint.bin'),
            (Convert-HexToBytes (Invoke-Psql $pg "SELECT encode(snapshot, 'hex') FROM metadata_state WHERE vol = $vol")))
        $state = Invoke-Psql $pg @"
SELECT json_build_object(
  'release', '$tag',
  'release_asset', '$($release.Asset)',
  'release_asset_sha256', '$($release.Sha256)',
  'metadata_format_version', metadata_format_version,
  'version', version,
  'checkpoint_version', checkpoint_version,
  'event_log_prune_floor', event_log_prune_floor,
  'checkpoint_sha256', encode(checkpoint_sha256, 'hex'),
  'checkpoint_publication_state', checkpoint_publication_state,
  'checkpoint_generation', checkpoint_generation,
  'event_log_rows', (SELECT count(*) FROM event_log e WHERE e.vol = m.vol),
  'bootstrap_checkpoint_lease_rows', (SELECT count(*) FROM bootstrap_checkpoint_leases l WHERE l.vol = m.vol),
  'schema_components', (SELECT coalesce(json_agg(json_build_object('component', c.component, 'version', c.version) ORDER BY c.component), '[]'::json)
                        FROM studiofs_schema_components c)
)
FROM metadata_state m WHERE vol = $vol
"@
        Set-Content -NoNewline -Encoding utf8NoBOM (Join-Path $out 'metadata-state.json') (($state | ConvertFrom-Json | ConvertTo-Json -Depth 5).Replace("`r`n", "`n") + "`n")
        $events = Invoke-Psql $pg @"
SELECT coalesce(json_agg(json_build_object(
  'batch_version', batch_version,
  'event_type', event_type,
  'event_payload_hex', encode(event_payload, 'hex')) ORDER BY seq_id), '[]'::json)
FROM event_log WHERE vol = $vol
"@
        Set-Content -NoNewline -Encoding utf8NoBOM (Join-Path $out 'event-log.json') ((ConvertTo-Json -Depth 5 -InputObject @($events | ConvertFrom-Json)).Replace("`r`n", "`n") + "`n")

        $db = Join-Path $clientRoot "meta/$volume/$volume.db"
        if (-not (Test-Path $db)) { throw "$tag init did not create the local cache $db" }
        Copy-Item -Force $db (Join-Path $out 'local-cache.redb')
        Write-Host "captured $tag -> $out"
    }
    finally {
        Remove-Item Env:STUDIOFS_CLIENT_ROOT -ErrorAction SilentlyContinue
        if (-not $KeepContainers) { docker rm -f $pg $s3 2>$null | Out-Null }
    }
}
