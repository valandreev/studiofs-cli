<#
.SYNOPSIS
  Capture persisted bytes of a volume formatted by a published StudioFS release.

.DESCRIPTION
  SFS-1002. For each release tag this script:

    1. downloads the published Windows binary with `gh release download` and
       verifies the zip against its published SHA-256;
    2. runs the opt-in `studiofs-e2e` scenario `published-volume-fixture-capture`
       with that binary and `--infra compose`. The runner owns PostgreSQL and
       RustFS (docker/compose.e2e.yml) and its fixed test-only credentials;
    3. copies the scenario artifacts into
       crates/studiofs-meta/tests/fixtures/published-<tag>/ with LF line endings:

         format-info.json       metadata_state.format_info (shared FormatInfo JSON)
         serving-checkpoint.bin metadata_state.snapshot (serving checkpoint bytes)
         metadata-state.json    metadata_state scalars and schema components
         event-log.json         event_log rows written by init (hex payloads)
         local-cache.redb       the local redb metadata cache created by init

  The volume master key inside FormatInfo is generated by the published
  `init` for a throwaway volume and protects no data.

  After a run, update the SHA-256 values in
  crates/studiofs-meta/tests/fixtures/baseline-0.2.5/manifest.json (the drift
  test prints the actual digest) and record the reason for the capture.

.EXAMPLE
  pwsh tools/fixtures/capture-published-volume-fixtures.ps1
  pwsh tools/fixtures/capture-published-volume-fixtures.ps1 -Tags v0.2.4
#>
[CmdletBinding()]
param(
    [string[]] $Tags = @('v0.2.2', 'v0.2.4')
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path
$workRoot = Join-Path $repoRoot 'target/sfs-1002-published'
$fixtureRoot = Join-Path $repoRoot 'crates/studiofs-meta/tests/fixtures'
$scenario = 'published-volume-fixture-capture'

# Windows release asset names changed between releases. The SHA-256 values are
# pinned here and in the fixture manifest, so a replaced release asset is
# refused even if its own published .sha256 file was replaced with it.
$assetByTag = @{
    'v0.2.2' = 'studiofs-0.2.2-x86_64-pc-windows-msvc.zip'
    'v0.2.4' = 'studiofs-0.2.4-x86_64-pc-windows.zip'
}
$pinnedSha256ByTag = @{
    'v0.2.2' = '10748f832568b8f918b1b316e48d819139ff9aaaccb190a77abf5aca5cbebff0'
    'v0.2.4' = 'cbd877327d86adc2e77395578298f9cc5f9a3d4a517559f9d8904698b805c3a6'
}

function Invoke-Native {
    param([string] $What, [scriptblock] $Command)
    $output = & $Command 2>&1
    if ($LASTEXITCODE -ne 0) {
        throw "$What failed (exit $LASTEXITCODE): $($output | Out-String)"
    }
    $output
}

function Get-ReleaseBinary {
    param([string] $Tag)
    $asset = $assetByTag[$Tag]
    if (-not $asset) { throw "no Windows asset name recorded for $Tag" }
    $dir = Join-Path $workRoot $Tag
    New-Item -ItemType Directory -Force $dir | Out-Null
    Invoke-Native "download $Tag" { gh release download $Tag --pattern $asset --pattern "$asset.sha256" --dir $dir --clobber } | Out-Null
    $zip = Join-Path $dir $asset
    $expected = ((Get-Content "$zip.sha256" -Raw).Trim() -split '\s+')[0].ToLowerInvariant()
    $actual = (Get-FileHash -Algorithm SHA256 $zip).Hash.ToLowerInvariant()
    if ($expected -ne $actual) { throw "$asset SHA-256 mismatch: expected $expected, got $actual" }
    if ($pinnedSha256ByTag[$Tag] -ne $actual) {
        throw "$asset SHA-256 $actual differs from the pinned $($pinnedSha256ByTag[$Tag])"
    }
    $bin = Join-Path $dir 'bin'
    Expand-Archive -Force $zip $bin
    $exe = Get-ChildItem -Recurse -Filter studiofs.exe $bin | Select-Object -First 1
    if (-not $exe) { throw "studiofs.exe not found in $asset" }
    $exe.FullName
}

Push-Location $repoRoot
try {
    foreach ($tag in $Tags) {
        $exe = Get-ReleaseBinary $tag
        $runId = "sfs-1002-capture-$($tag.Replace('.', '-'))"
        $runDir = Join-Path $repoRoot "target/e2e-runs/$runId"
        if (Test-Path $runDir) { Remove-Item -Recurse -Force $runDir }
        Invoke-Native "$tag capture scenario" {
            cargo run -q -p studiofs-e2e -- run $scenario --studiofs-bin $exe `
                --infra compose --run-id $runId --retain always
        } | Out-Null

        $artifacts = Join-Path $runDir "artifacts/scenarios/$scenario/published-volume"
        $out = Join-Path $fixtureRoot "published-$tag"
        New-Item -ItemType Directory -Force $out | Out-Null
        foreach ($file in Get-ChildItem -File $artifacts) {
            $target = Join-Path $out $file.Name
            if ($file.Extension -eq '.json') {
                $text = [IO.File]::ReadAllText($file.FullName).Replace("`r`n", "`n")
                [IO.File]::WriteAllText($target, $text)
            }
            else {
                Copy-Item -Force $file.FullName $target
            }
        }
        Write-Host "captured $tag -> $out (run $runDir)"
    }
}
finally {
    Pop-Location
}
